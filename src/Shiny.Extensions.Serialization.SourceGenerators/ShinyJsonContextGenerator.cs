    static string Sanitize(string name)
    {
        var sb = new StringBuilder(name.Length);
        for (int i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsLetterOrDigit(c))
                sb.Append(c);
            else if (c == '.' || c == '_' || c == '-' || c == '+')
                sb.Append('_');
        }
        if (sb.Length == 0 || char.IsDigit(sb[0]))
            sb.Insert(0, '_');
        return sb.ToString();
    }


    readonly struct HostInfo : IEquatable<HostInfo>
    {
        public HostInfo(string fullyQualifiedName) { FullyQualifiedName = fullyQualifiedName; }
        public string FullyQualifiedName { get; }
        public bool Equals(HostInfo other) => FullyQualifiedName == other.FullyQualifiedName;
        public override bool Equals(object? obj) => obj is HostInfo h && Equals(h);
        public override int GetHashCode() => StringComparer.Ordinal.GetHashCode(FullyQualifiedName);
    }


    readonly struct IncludeInfo : IEquatable<IncludeInfo>
    {
        public IncludeInfo(string fullyQualifiedName, Location? location, Diagnostic? diagnostic)
        {
            FullyQualifiedName = fullyQualifiedName;
            Location = location;
            Diagnostic = diagnostic;
        }
        public string FullyQualifiedName { get; }
        public Location? Location { get; }
        public Diagnostic? Diagnostic { get; }

        // Location intentionally excluded from equality so incremental caching ignores file-position drift.
        public bool Equals(IncludeInfo other) => FullyQualifiedName == other.FullyQualifiedName && ReferenceEquals(Diagnostic, other.Diagnostic);
        public override bool Equals(object? obj) => obj is IncludeInfo i && Equals(i);
        public override int GetHashCode() => StringComparer.Ordinal.GetHashCode(FullyQualifiedName);
    }
